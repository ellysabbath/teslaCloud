# certificates/views.py

"""
Certificate views.

Design
------
* A certificate is created lazily the first time it is needed for a
  given (user, course) pair. Enrollments are the source of truth.
* There is no manual issue, revoke, or restore. Every certificate
  is generated by ``ensure_certificate`` and can be looked up by its
  UUID (``Certificate.id``) for public verification.
* Admins can hide (unpublish) or publish a certificate. Hidden
  certificates fail public verification and cannot be downloaded
  by their owner.
* The admin list exposes every certificate in the system, with
  search, status, and published filters.
"""

from django.db.models import Q
from django.shortcuts import get_object_or_404
from django.utils import timezone

from rest_framework import status
from rest_framework.permissions import AllowAny, IsAuthenticated
from rest_framework.response import Response
from rest_framework.views import APIView

from courses.models import Course
from enrollments.models import CourseEnrollment

from .models import Certificate
from .serializers import CertificateSerializer
from .services import (
    ensure_certificate,
    ensure_images,
    sync_certificates_for_user,
)
from .utils import render_certificate_base64


# ============================================================
# HELPERS
# ============================================================
def _is_first_certificate(cert: Certificate, viewer) -> bool:
    """
    True if this certificate should be shown watermarked to the
    given viewer:

      * viewer is not the owner  → True (always watermarked)
      * owner's earliest cert    → True
      * any later cert for owner → False
    """
    if viewer is None or viewer != cert.user:
        return True
    first = (
        Certificate.objects
        .filter(user=cert.user)
        .order_by("issued_at")
        .first()
    )
    return first is not None and first.id == cert.id


def _decorate(cert: Certificate, viewer) -> dict:
    """
    Serialize a certificate and attach the display flags the
    frontend relies on:

      * displayImageDataUrl — the base64 PNG to render
      * watermarked         — True/False
      * canDownload         — True only for published, non-watermarked
      * isPublished         — mirrors the DB flag
    """
    ensure_images(cert)
    cert.refresh_from_db()

    watermarked = _is_first_certificate(cert, viewer)
    data = CertificateSerializer(cert).data
    data["displayImageDataUrl"] = (
        data["image_watermarked_data_url"]
        if watermarked
        else data["image_data_url"]
    )
    data["watermarked"] = watermarked
    # Owner can download only if certificate is published AND not watermarked.
    data["canDownload"] = (not watermarked) and bool(cert.is_published)
    data["isPublished"] = bool(cert.is_published)
    return data


def _is_admin(user) -> bool:
    return getattr(user, "role", "") in ("admin", "super-admin")


# ============================================================
# GET /api/certificates/mine/
# ============================================================
class MyCertificatesView(APIView):
    permission_classes = [IsAuthenticated]

    def get(self, request):
        certs = sync_certificates_for_user(request.user)
        certs.sort(
            key=lambda c: c.issued_at or timezone.now(),
            reverse=True,
        )
        return Response(
            {
                "success": True,
                "data": [_decorate(c, request.user) for c in certs],
            }
        )


# ============================================================
# GET /api/certificates/<uuid>/
# ============================================================
class CertificateDetailView(APIView):
    permission_classes = [IsAuthenticated]

    def get(self, request, certificate_id):
        cert = get_object_or_404(
            Certificate.objects.select_related("course", "user"),
            id=certificate_id,
        )

        is_owner = cert.user_id == request.user.id
        if not (is_owner or _is_admin(request.user)):
            return Response(
                {"success": False, "message": "Not allowed"},
                status=status.HTTP_403_FORBIDDEN,
            )

        return Response(
            {"success": True, "data": _decorate(cert, request.user)}
        )


# ============================================================
# GET /api/certificates/preview/<course_id>/
# ============================================================
class CertificatePreviewView(APIView):
    permission_classes = [IsAuthenticated]

    def get(self, request, course_id):
        course = get_object_or_404(Course, id=course_id)

        enrolled = CourseEnrollment.objects.filter(
            user=request.user, course=course
        ).exists()

        if enrolled:
            cert = ensure_certificate(request.user, course)
            return Response(
                {"success": True, "data": _decorate(cert, request.user)}
            )

        # Not enrolled — watermarked preview only, no download.
        png = render_certificate_base64(
            certificate_number="PREVIEW",
            candidate_name=(
                request.user.full_name or request.user.username
            ),
            course_title=course.title,
            grade=None,
            final_percentage=None,
            issue_date=timezone.now(),
            verification_url="",
            watermarked=True,
        )
        return Response(
            {
                "success": True,
                "data": {
                    "displayImageDataUrl": png,
                    "watermarkedImageDataUrl": png,
                    "cleanImageDataUrl": None,
                    "watermarked": True,
                    "canDownload": False,
                    "certificate_number": None,
                    "courseTitle": course.title,
                },
            }
        )


# ============================================================
# GET /api/certificates/verify/<uuid>/
# ============================================================
class CertificateVerifyView(APIView):
    permission_classes = [AllowAny]

    def get(self, request, certificate_id):
        try:
            cert = (
                Certificate.objects
                .select_related("user", "course")
                .get(id=certificate_id)
            )
        except Certificate.DoesNotExist:
            return Response(
                {"success": True, "data": {"valid": False}}
            )

        if cert.status == "revoked":
            return Response(
                {
                    "success": True,
                    "data": {
                        "valid": False,
                        "reason": "revoked",
                    },
                }
            )

        if not cert.is_published:
            return Response(
                {
                    "success": True,
                    "data": {
                        "valid": False,
                        "reason": "unpublished",
                    },
                }
            )

        return Response(
            {
                "success": True,
                "data": {
                    "valid": True,
                    "certificateId": str(cert.id),
                    "certificateNumber": cert.certificate_number,
                    "studentName": (
                        cert.user.full_name or cert.user.username
                    ),
                    "courseTitle": cert.course.title,
                    "issuedAt": cert.issued_at,
                },
            }
        )


