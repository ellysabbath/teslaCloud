# GET /api/certificates/admin/
# ============================================================
class AdminCertificateListView(APIView):
    permission_classes = [IsAuthenticated]

    def get(self, request):
        if not _is_admin(request.user):
            return Response(
                {"success": False, "message": "Not allowed"},
                status=status.HTTP_403_FORBIDDEN,
            )

        qs = (
            Certificate.objects
            .select_related("course", "user")
            .order_by("-issued_at")
        )

        search = (request.query_params.get("search") or "").strip()
        status_filter = (
            request.query_params.get("status") or ""
        ).strip()
        published_filter = (
            request.query_params.get("published") or ""
        ).strip()

        if status_filter and status_filter != "all":
            qs = qs.filter(status=status_filter)

        if published_filter in ("true", "false"):
            qs = qs.filter(is_published=(published_filter == "true"))

        if search:
            qs = qs.filter(
                Q(certificate_number__icontains=search)
                | Q(id__icontains=search)
                | Q(user__full_name__icontains=search)
                | Q(user__username__icontains=search)
                | Q(course__title__icontains=search)
            )

        results = []
        for cert in qs:
            ensure_images(cert)
            cert.refresh_from_db()
            data = CertificateSerializer(cert).data
            data["displayImageDataUrl"] = data["image_data_url"]
            data["watermarked"] = False
            data["canDownload"] = bool(cert.is_published)
            data["isPublished"] = bool(cert.is_published)
            results.append(data)

        return Response({"success": True, "data": results})


# ============================================================
# PATCH /api/certificates/admin/<uuid>/publish/
# body: { "is_published": true | false }
# ============================================================
class AdminCertificatePublishView(APIView):
    permission_classes = [IsAuthenticated]

    def patch(self, request, certificate_id):
        if not _is_admin(request.user):
            return Response(
                {"success": False, "message": "Not allowed"},
                status=status.HTTP_403_FORBIDDEN,
            )

        cert = get_object_or_404(Certificate, id=certificate_id)

        if "is_published" not in request.data:
            return Response(
                {"success": False, "message": "is_published is required"},
                status=status.HTTP_400_BAD_REQUEST,
            )

        cert.is_published = bool(request.data["is_published"])
        cert.save(update_fields=["is_published", "updated_at"])

        ensure_images(cert)
        cert.refresh_from_db()

        data = CertificateSerializer(cert).data
        data["displayImageDataUrl"] = data["image_data_url"]
        data["watermarked"] = False
        data["canDownload"] = bool(cert.is_published)
        data["isPublished"] = bool(cert.is_published)

        return Response({"success": True, "data": data})